'use strict';
const assert = require('node:assert/strict');
const { BrowserWindow } = require('electron');
const { setTimeout: pause } = require('node:timers/promises');
const { epub } = require('../../fixtures.cjs');

module.exports = async (ui) => {
  const phrase = '窗口变化后仍应命中🚢原文';
  const bytes = epub({ images: true, body: `<p>这是用于界面验证的合成 EPUB 起始段落。</p><p>今天沿着纸河散步，${phrase}，看见不同的故事。</p><p>纸河<img src="images/pixel.png" alt="字形"/>之后仍有文字可以选择。</p>` });
  const file = ui.fixture('合成排版矩阵.epub', bytes);
  const panel = 'section[aria-label="本书划线与批注"]';
  const body = 'article[aria-label="正文"]';
  const selected = `${body} [data-block-index="1"]`;
  const mark = `${body} [data-block-index="1"] [data-highlight-id]`;
  const selectOption = async (name, value) => ui.eval((label, option) => {
    const field = [...document.querySelectorAll('label')].find(el => el.innerText.trim().startsWith(label))?.querySelector('select');
    if (!field) throw new Error(`Missing selector: ${label}`);
    field.value = option;
    field.dispatchEvent(new Event('change', { bubbles: true }));
  }, name, value);
  const waitMark = () => ui.waitFor((s, q) => [...document.querySelectorAll(s)].map(e => e.textContent).join('') === q, [mark, phrase]);
  await ui.waitFor(() => document.querySelector('h1')?.innerText === '书架');
  ui.queueImport(file);
  await ui.clickText('导入书籍');
  await ui.wait('article button h2');
  await ui.click('article button h2');
  await ui.wait(selected);
  const start = await ui.eval((s, p) => document.querySelector(s).textContent.indexOf(p), selected, phrase);
  assert.ok(start >= 0);
  assert.equal(await ui.select({ selector: selected, offset: start }, { selector: selected, offset: start + phrase.length }), phrase);
  await ui.waitFor(() => [...document.querySelectorAll('button')].some(e => e.textContent === '划线' && !e.disabled));
  await ui.clickText('划线');
  await waitMark();
  const anchorId = await ui.eval((s) => document.querySelector(s).dataset.highlightId, mark);
  // Test real Chromium element-container endpoints next to an image run.
  assert.equal(await ui.eval((s) => {
    const p = document.querySelector(`${s} [data-block-index="2"]`);
    const range = document.createRange();
    range.setStart(p, 0);
    range.setEnd(p, 1);
    const selection = window.getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    return selection.toString();
  }, body), '纸河');
  await ui.waitFor(() => [...document.querySelectorAll('button')].some(e => e.textContent === '划线' && !e.disabled));
  await ui.clickText('划线');
  await ui.waitFor((s) => [...document.querySelectorAll(`${s} [data-block-index="2"] [data-highlight-id]`)].map(e => e.textContent).join('') === '纸河', [body]);
  await ui.click(mark);
  await ui.wait(panel);
  await ui.clickText('增大字号');
  await ui.clickText('增大字号');
  await selectOption('行距', '2');
  await selectOption('字体', 'serif');
  await selectOption('边距', '40');
  await ui.clickText('护眼主题');
  await waitMark();
  await ui.clickText('定位原文');
  await ui.waitFor((s, q) => [...document.querySelectorAll(`${s} [data-emphasis="jump"]`)].map(e => e.textContent).join('') === q, [body, phrase]);
  assert.equal(await ui.eval((s) => document.querySelector(s).dataset.highlightId, mark), anchorId);
  await pause(150);
  await ui.screenshot('07-epub-typography-sepia');
  const win = BrowserWindow.getAllWindows()[0];
  win.setSize(620, 720);
  await ui.waitFor(() => innerWidth <= 640);
  await pause(250);
  await waitMark();
  assert.equal(await ui.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  const panelHeight = await ui.eval((s) => document.querySelector(s).parentElement.clientHeight, panel);
  assert.ok(panelHeight >= 160, `Narrow panel clipped to ${panelHeight}px`);
  await ui.screenshot('08-epub-narrow-panel');
  await ui.clickText('关闭', { selector: `${panel} button` });
  await ui.clickText('分页');
  await waitMark();
  assert.equal(await ui.eval((s) => document.querySelector(s).dataset.highlightId, mark), anchorId);
  await ui.click(mark);
  await ui.clickText('定位原文');
  await ui.waitFor((s) => !!document.querySelector(`${s} [data-emphasis="jump"]`), [body]);
  await pause(150);
  await ui.screenshot('09-epub-narrow-page');
  ui.log('OK: EPUB anchor retained through font size, line spacing, serif font, margins, sepia theme, 620px window and pagination');
};
